if (file.exists(".Renviron")) readRenviron(".Renviron")

base_url   <- Sys.getenv("DHIS2_URL")
dhis2_user <- Sys.getenv("DHIS2_USER")
dhis2_pass <- Sys.getenv("DHIS2_PASS")

if (dhis2_user == "" || dhis2_pass == "") {
  stop("Credenciais DHIS2_USER / DHIS2_PASS nao definidas no .Renviron.")
}

output_dir <- here::here("data")
if (!dir.exists(output_dir)) dir.create(output_dir, recursive = TRUE)

output_tmp <- file.path(output_dir, "Data_BES_tmp.xls")
output_xls <- file.path(output_dir, "Data_BES.xls")

max_tentativas <- 3
sucesso <- FALSE

for (tentativa in 1:max_tentativas) {

  message(sprintf("Tentativa %d de %d: a descarregar dados do SISMA...", tentativa, max_tentativas))

  resp <- GET(
    url = api_url,
    authenticate(dhis2_user, dhis2_pass),
    write_disk(output_tmp, overwrite = TRUE),
    timeout(300)
  )

  if (status_code(resp) == 200 && file.exists(output_tmp) && file.info(output_tmp)$size > 0) {
    sucesso <- TRUE
    message("Download concluido com sucesso.")
    break
  } else {
    corpo_erro <- tryCatch(content(resp, as = "text", encoding = "UTF-8"), error = function(e) "N/A")
    message(sprintf("Falha (HTTP %s). Corpo da resposta: %s", status_code(resp), substr(corpo_erro, 1, 300)))
    if (file.exists(output_tmp)) file.remove(output_tmp)
    if (tentativa < max_tentativas) Sys.sleep(5)
  }
}

if (!sucesso) {
  stop("Nao foi possivel descarregar os dados do SISMA apos varias tentativas.")
}

dados <- read_excel(output_tmp)

if (ncol(dados) == 0 || nrow(dados) == 0) {
  stop("Ficheiro descarregado esta vazio ou sem colunas.")
}

file.rename(output_tmp, output_xls)

message(sprintf("Ficheiro final guardado em: %s (%d linhas, %d colunas)", output_xls, nrow(dados), ncol(dados)))
